enum class AppLanguage(val tag: String) {
    FR("fr"),
    EN("en"),
    ;

    companion object {
        val fallback = EN

        fun fromTag(tag: String?): AppLanguage? {
            if (tag.isNullOrBlank()) return null
            val language = Locale.forLanguageTag(tag).language.lowercase(Locale.ROOT)
            return entries.firstOrNull { it.tag == language }
        }

        fun fromLocale(locale: Locale): AppLanguage {
            return fromTag(locale.toLanguageTag()) ?: fallback
        }
    }
}

enum class AppLanguagePreference(
    val storageValue: String,
    val forcedLanguageTag: String?,
) {
    SYSTEM("system", null),
    FR("fr", "fr"),
    EN("en", "en"),
    ;

    companion object {
        fun fromStorage(value: String?): AppLanguagePreference {
            return entries.firstOrNull { it.storageValue == value } ?: SYSTEM
        }
    }
}

