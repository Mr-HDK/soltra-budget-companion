private val catalogs = mapOf(
    AppLanguage.FR to frCatalog,
    AppLanguage.EN to enCatalog,
)

@Stable
class AppStrings internal constructor(
    val language: AppLanguage,
) {
    fun get(key: AppTextKey): String {
        val selectedCatalog = catalogs[language].orEmpty()
        val fallbackCatalog = catalogs[AppLanguage.fallback].orEmpty()
        return selectedCatalog[key] ?: fallbackCatalog[key] ?: key.name
    }
}

val LocalAppStrings = staticCompositionLocalOf { AppStrings(AppLanguage.fallback) }

fun resolveAppLanguage(forcedLanguageTag: String?, systemLocale: Locale): AppLanguage {
    return AppLanguage.fromTag(forcedLanguageTag) ?: AppLanguage.fromLocale(systemLocale)
}

fun resolveLocale(preference: AppLanguagePreference, systemLocale: Locale): Locale {
    return preference.forcedLanguageTag?.let(Locale::forLanguageTag) ?: systemLocale
}

@Composable
fun AppI18nProvider(
    forcedLanguageTag: String? = null,
    content: @Composable () -> Unit,
) {
    val configuration = LocalConfiguration.current
    val systemLocale = remember(configuration) { configuration.primaryLocale() }
    val language = remember(forcedLanguageTag, systemLocale) {
        resolveAppLanguage(forcedLanguageTag, systemLocale)
    }
    val strings = remember(language) { AppStrings(language) }

    CompositionLocalProvider(LocalAppStrings provides strings) {
        content()
    }
}

@Composable
fun localized(key: AppTextKey): String {
    return LocalAppStrings.current.get(key)
}

private fun Configuration.primaryLocale(): Locale {
    if (locales.size() > 0) {
        return locales[0]
    }
    @Suppress("DEPRECATION")
    return locale ?: Locale.getDefault()
}

